"""Explicit, additive initialization of Pongdang's own collection schema."""

import argparse
from contextlib import contextmanager

import psycopg
from psycopg import sql

from app.attachments.migrations import migrate_attachments
from app.config import Settings
from app.data_reader import CATALOG
from app.travel.migrations import migrate_travel
from app.water_index.migrations import migrate_water_index

SCHEMA = "pongdang_data"
VERSION = 10
TYPES = {
    "text": "text",
    "number": "double precision",
    "boolean": "boolean",
    "json": "jsonb",
    "datetime": "timestamptz",
    "date": "date",
}


@contextmanager
def connect(settings: Settings):
    if settings.postgres_host.lower() == "cksdb":
        raise ValueError("The shared legacy database is not a Pongdang write target")
    if settings.postgres_db not in {"pongdang", "pongdang_test"}:
        raise ValueError("Unexpected Pongdang database")
    with psycopg.connect(
        host=settings.postgres_host,
        port=settings.postgres_port,
        dbname=settings.postgres_db,
        user=settings.postgres_user,
        password=settings.postgres_password.get_secret_value(),
        connect_timeout=3,
        options="-c statement_timeout=10000 -c lock_timeout=3000",
    ) as connection:
        if connection.info.server_version < 180000:
            raise ValueError("Pongdang writes require its PostgreSQL 18 database")
        yield connection


def initialize(settings: Settings) -> bool:
    with connect(settings) as connection:
        connection.execute("SELECT pg_advisory_xact_lock(hashtext('pongdang-schema'))")
        if connection.execute("SELECT to_regnamespace('pongdang_data')").fetchone()[0]:
            # Never adopt an unknown schema or overwrite existing tables/data.
            row = connection.execute(
                "SELECT version FROM pongdang_data.schema_version WHERE id=1"
            ).fetchone()
            if row in {(1,), (2,)}:
                migrate_collection(connection)
                migrate_water_index(connection)
                migrate_features(connection)
                migrate_place_provenance(connection)
                migrate_ai_concierge(connection)
                migrate_travel(connection)
                migrate_attachments(connection)
                migrate_regional_collection(connection)
                return True
            if row == (3,):
                migrate_water_index(connection)
                migrate_features(connection)
                migrate_place_provenance(connection)
                migrate_ai_concierge(connection)
                migrate_travel(connection)
                migrate_attachments(connection)
                migrate_regional_collection(connection)
                return True
            if row == (4,):
                migrate_features(connection)
                migrate_place_provenance(connection)
                migrate_ai_concierge(connection)
                migrate_travel(connection)
                migrate_attachments(connection)
                migrate_regional_collection(connection)
                return True
            if row == (5,):
                migrate_place_provenance(connection)
                migrate_ai_concierge(connection)
                migrate_travel(connection)
                migrate_attachments(connection)
                migrate_regional_collection(connection)
                return True
            if row == (6,):
                migrate_ai_concierge(connection)
                migrate_travel(connection)
                migrate_attachments(connection)
                migrate_regional_collection(connection)
                return True
            if row == (7,):
                migrate_travel(connection)
                migrate_attachments(connection)
                migrate_regional_collection(connection)
                return True
            if row == (8,):
                migrate_attachments(connection)
                migrate_regional_collection(connection)
                return True
            if row == (9,):
                migrate_regional_collection(connection)
                return True
            if row != (VERSION,):
                raise ValueError("Unrecognized Pongdang schema version")
            return False
        connection.execute("CREATE SCHEMA pongdang_data")
        connection.execute("REVOKE ALL ON SCHEMA pongdang_data FROM PUBLIC")
        for dataset in CATALOG:
            columns = []
            for column in dataset["columns"]:
                name = column["key"]
                kind = (
                    "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
                    if name == "id"
                    else "bigint"
                    if name.endswith("_id") and column["type"] == "number"
                    else TYPES[column["type"]]
                )
                columns.append(
                    sql.SQL("{} {}").format(sql.Identifier(name), sql.SQL(kind))
                )
            connection.execute(
                sql.SQL("CREATE TABLE {} ({})").format(
                    sql.Identifier(SCHEMA, dataset["table"]), sql.SQL(",").join(columns)
                )
            )
        connection.execute(
            "ALTER TABLE pongdang_data.conditions_observationsnapshot "
            "ADD FOREIGN KEY (spot_id) REFERENCES pongdang_data.spots_waterspot(id), "
            "ADD UNIQUE (provider,provider_record_id,spot_id)"
        )
        connection.execute(
            "ALTER TABLE pongdang_data.conditions_observationmetric "
            "ADD FOREIGN KEY (snapshot_id) "
            "REFERENCES pongdang_data.conditions_observationsnapshot(id), "
            "ADD UNIQUE (snapshot_id,name)"
        )
        connection.execute(
            "CREATE TABLE pongdang_data.ingestion_batches ("
            "provider text NOT NULL, batch_key text NOT NULL, digest text NOT NULL, "
            "created_at timestamptz NOT NULL DEFAULT now(), "
            "PRIMARY KEY(provider,batch_key))"
        )
        connection.execute(
            "CREATE TABLE pongdang_data.schema_version "
            "(id integer PRIMARY KEY CHECK(id=1), version integer NOT NULL)"
        )
        connection.execute(
            "INSERT INTO pongdang_data.schema_version VALUES (1,%s)", [VERSION]
        )
        migrate_collection(connection)
        migrate_water_index(connection)
        migrate_features(connection)
        migrate_place_provenance(connection)
        migrate_ai_concierge(connection)
        migrate_travel(connection)
        migrate_attachments(connection)
        migrate_regional_collection(connection)
    return True


def migrate_regional_collection(connection):
    """Explicit v9 -> v10: source-confirmed regions and resumable catalog scopes."""
    from app.ingestion.administrative import migrate_place_regions
    from app.ingestion.gangwon import migrate_tourism_scopes

    migrate_place_regions(connection)
    migrate_tourism_scopes(connection)
    connection.execute(
        "CREATE INDEX IF NOT EXISTS collection_place_spot_idx "
        "ON pongdang_data.collection_place(spot_id)"
    )
    connection.execute("UPDATE pongdang_data.schema_version SET version=10 WHERE id=1")


def migrate_ai_concierge(connection):
    """Explicit v6 -> v7: retain old budget totals, add admission/usage records."""
    from app.ai.budget import migrate_ai

    migrate_ai(connection)
    connection.execute("UPDATE pongdang_data.schema_version SET version=7 WHERE id=1")


def migrate_place_provenance(connection):
    """Explicit v5 -> v6: preserve nullable provider catalogue timestamps."""
    connection.execute(
        "ALTER TABLE pongdang_data.collection_place "
        "ADD COLUMN IF NOT EXISTS source_created_at timestamptz, "
        "ADD COLUMN IF NOT EXISTS source_modified_at timestamptz"
    )
    connection.execute(
        "ALTER TABLE pongdang_data.collection_station "
        "ADD COLUMN IF NOT EXISTS source_valid_from timestamptz, "
        "ADD COLUMN IF NOT EXISTS source_valid_until timestamptz"
    )
    connection.execute("UPDATE pongdang_data.schema_version SET version=6 WHERE id=1")


